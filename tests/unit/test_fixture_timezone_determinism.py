"""The fixture corpus is byte-reproducible under any host timezone.

The generator runs in a subprocess per zone in :data:`ZONES`, since the local zone is resolved from
the child's environment and setting `TZ` in this process would not change it.
"""

from __future__ import annotations

import json
import os
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

import pytest
from fixtures.generate import _iso
from scripts import proc_run

REPO_ROOT = Path(__file__).resolve().parents[2]

#: Fixture file names the generator emits, mirroring `GeneratedCorpus.as_mapping`.
CORPUS_FILES: tuple[str, ...] = (
    "accounts.json",
    "contacts.json",
    "opportunities.json",
    "activities.json",
    "notes.json",
)

#: Zones the corpus must be identical under: UTC, a negative whole-hour offset, and a half-hour
#: offset.
ZONES: tuple[str, ...] = ("UTC", "America/Los_Angeles", "Asia/Kolkata")

_TIME_OF_DAY = re.compile(r"T\d{2}:\d{2}:\d{2}Z")


def _generate_under(tz: str, out_dir: Path) -> dict[str, bytes]:
    """Run the generator in a subprocess with ``TZ=tz`` and return each output file's bytes."""
    env = {**os.environ, "TZ": tz}
    completed = proc_run.run(
        [sys.executable, "-m", "fixtures.generate", "--tenant", "demo", "--out", str(out_dir)],
        cwd=REPO_ROOT,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert completed.returncode == 0, (
        f"generator failed under TZ={tz}: rc={completed.returncode}\n{completed.stderr}"
    )
    return {name: (out_dir / name).read_bytes() for name in CORPUS_FILES}


@pytest.fixture(scope="module")
def corpora_by_zone(tmp_path_factory: pytest.TempPathFactory) -> dict[str, dict[str, bytes]]:
    """Generate the corpus once per zone in :data:`ZONES`, into a scratch dir per zone."""
    return {tz: _generate_under(tz, tmp_path_factory.mktemp(tz.replace("/", "-"))) for tz in ZONES}


def test_every_output_file_is_present_under_every_zone(
    corpora_by_zone: dict[str, dict[str, bytes]],
) -> None:
    """Every zone emits every corpus file, each non-empty."""
    for tz, corpus in corpora_by_zone.items():
        assert set(corpus) == set(CORPUS_FILES), f"TZ={tz} emitted {sorted(corpus)}"
        for name, payload in corpus.items():
            assert payload, f"TZ={tz} emitted an empty {name}"


@pytest.mark.parametrize("tz", [tz for tz in ZONES if tz != "UTC"])
def test_corpus_is_byte_identical_to_the_utc_corpus(
    tz: str, corpora_by_zone: dict[str, dict[str, bytes]]
) -> None:
    """Rendering must not consult the host zone: every file matches its UTC-generated bytes."""
    utc_corpus = corpora_by_zone["UTC"]
    other = corpora_by_zone[tz]
    diverged = [name for name in CORPUS_FILES if other[name] != utc_corpus[name]]
    assert not diverged, f"TZ={tz} diverged from TZ=UTC in {diverged}"


def test_every_rendered_timestamp_is_utc_midnight(
    corpora_by_zone: dict[str, dict[str, bytes]],
) -> None:
    """Every rendered time-of-day in every zone is exactly ``T00:00:00Z``."""
    for tz, corpus in corpora_by_zone.items():
        for name, payload in corpus.items():
            found = set(_TIME_OF_DAY.findall(payload.decode("utf-8")))
            assert found == {"T00:00:00Z"}, f"TZ={tz} {name} rendered times-of-day {sorted(found)}"


def test_committed_corpus_matches_the_utc_generation(
    corpora_by_zone: dict[str, dict[str, bytes]],
) -> None:
    """The committed fixture bytes equal the UTC generation."""
    utc_corpus = corpora_by_zone["UTC"]
    for name, payload in utc_corpus.items():
        committed = (REPO_ROOT / "fixtures" / name).read_bytes()
        assert committed == payload, f"committed fixtures/{name} is not the UTC generation"


def test_committed_corpus_is_parseable_and_non_empty() -> None:
    """Every committed fixture file is a non-empty JSON array."""
    for name in CORPUS_FILES:
        items = json.loads((REPO_ROOT / "fixtures" / name).read_text(encoding="utf-8"))
        assert isinstance(items, list) and items, f"fixtures/{name} is not a non-empty JSON array"


def test_iso_rejects_a_naive_datetime() -> None:
    """`_iso` must refuse a naive datetime rather than resolve it against the host zone."""
    with pytest.raises(ValueError, match="naive datetime"):
        _iso(datetime(2026, 1, 1))
    assert _iso(datetime(2026, 1, 1, tzinfo=UTC)) == "2026-01-01T00:00:00Z"
